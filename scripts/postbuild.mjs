// Writes dist/.htaccess and dist/robots.txt for the chosen base path.
// Staging (STAGING=1) adds noindex everywhere and blocks crawlers.
import { writeFileSync } from 'node:fs';

const base = (process.env.SITE_BASE || '/').replace(/\/?$/, '/');
const staging = process.env.STAGING === '1';
const root = base === '/';

// Old WordPress URL -> new URL. Only applied when the site is at the root.
const redirects = {
  'offset-printing-solutions/fountain-solution': 'products/fountain-solution/',
  'offset-printing-solutions/plate-cleaner': 'products/plate-cleaner/',
  'offset-printing-solutions/plate-gum': 'products/plate-gum/',
  'offset-printing-solutions/roller-wash': 'products/roller-wash/',
  'offset-printing-solutions/isopropyl-alcohol': 'products/isopropyl-alcohol/',
  'offset-printing-solutions': 'products/',
  'top-quality-printing-solutions-and-manufacturing-chemical-solutions-for-offset-printing': 'about/',
  'importing-and-manufacturing-top-quality-products-for-offset-printing': '',
  'customer-service': 'contact/',
  // The old site also served each product at the root, and most internal links used these.
  'fountain-solution': 'products/fountain-solution/',
  'plate-cleaner': 'products/plate-cleaner/',
  'plate-gum': 'products/plate-gum/',
  'roller-wash': 'products/roller-wash/',
  'isopropyl-alcohol': 'products/isopropyl-alcohol/',
  home: '',
};

const csp = [
  "default-src 'self'",
  "script-src 'self' https://challenges.cloudflare.com",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  'frame-src https://challenges.cloudflare.com https://www.google.com https://maps.google.com',
  "form-action 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
].join('; ');

const htaccess = `# Generated by scripts/postbuild.mjs. Edit there, not here.
Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 ${base}404.html
AddDefaultCharset utf-8

<IfModule mod_rewrite.c>
RewriteEngine On
${root ? `
# One canonical address: https://www.jntsuppliers.com (only on the real domain)
RewriteCond %{HTTP_HOST} ^(www\\.)?jntsuppliers\\.com$ [NC]
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} ^jntsuppliers\\.com$ [NC]
RewriteRule ^ https://www.jntsuppliers.com%{REQUEST_URI} [R=301,L,NE]
` : `
RewriteCond %{HTTP_HOST} jntsuppliers\\.com$ [NC]
RewriteCond %{HTTPS} !=on
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L,NE]
`}
# Block dotfiles (except .well-known), backups, sources and any PHP but quote.php
RewriteRule (^|/)\\.(?!well-known/) - [F,L]
RewriteRule \\.(bak|old|orig|save|swp|sql|log|ini|sh|md|env|lock|zip|tar|gz)$ - [F,L,NC]
RewriteCond %{REQUEST_URI} !(^|/)quote\\.php$
RewriteRule \\.(php|phtml|phar)\\d?$ - [F,L,NC]
${root ? `
# Old WordPress URLs (keep search rankings)
${Object.entries(redirects)
  .map(([from, to]) => `RewriteRule ^${from.replace(/[.]/g, '\\.')}/?$ /${to} [R=301,L]`)
  .join('\n')}
RewriteRule ^(wp-admin|wp-login\\.php|wp-content|wp-includes|xmlrpc\\.php|wp-json) - [G,L]
RewriteRule ^feed/?$ - [G,L]
# WordPress archives and builder leftovers that no longer exist
RewriteRule ^(category|tag|author|cartflows_step|elementor-hf|\\d{4}/\\d{2})(/|$) - [G,L]
` : ''}
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "DENY"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
Header always set Cross-Origin-Opener-Policy "same-origin"
Header always set Content-Security-Policy "${csp}"
${root ? 'Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains" env=HTTPS' : ''}
${staging ? 'Header always set X-Robots-Tag "noindex, nofollow"' : ''}
Header unset X-Powered-By
Header always unset X-Powered-By

# Fingerprinted build assets never change; HTML is always revalidated.
<FilesMatch "\\.(css|js|woff2|webp|avif|png|jpe?g|svg)$">
  Header set Cache-Control "public, max-age=2592000"
</FilesMatch>
<If "%{REQUEST_URI} =~ m#/_astro/#">
  Header set Cache-Control "public, max-age=31536000, immutable"
</If>
<FilesMatch "\\.html$">
  Header set Cache-Control "no-cache"
</FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml
</IfModule>
`;

writeFileSync('dist/.htaccess', htaccess.replace(/\n{3,}/g, '\n\n'));

const robots = staging
  ? 'User-agent: *\nDisallow: /\n'
  : `User-agent: *\nAllow: /\n\nSitemap: https://www.jntsuppliers.com/sitemap-index.xml\n`;
writeFileSync('dist/robots.txt', robots);

console.log(`postbuild: .htaccess + robots.txt written (base ${base}${staging ? ', staging' : ''})`);
